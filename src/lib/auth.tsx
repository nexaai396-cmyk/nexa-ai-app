import { createContext, useContext, useEffect, useMemo, useState, type ReactNode } from 'react';
import type { Session } from '@supabase/supabase-js';
import { supabase } from './supabase';

/** The single email address permitted to access the Admin Command Center. */
export const ADMIN_EMAIL = 'nexaai396@gmail.com';

const UNAUTHORIZED_MSG = 'Unauthorized access: You do not have administrator permissions.';

interface AuthContextValue {
  session: Session | null;
  loading: boolean;
  isAdmin: boolean;
  signIn: (email: string, password: string) => Promise<{ error: string | null }>;
  signUp: (email: string, password: string) => Promise<{ error: string | null }>;
  signOut: () => Promise<void>;
}

const AuthContext = createContext<AuthContextValue | undefined>(undefined);

export function AuthProvider({ children }: { children: ReactNode }) {
  const [session, setSession] = useState<Session | null>(null);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    supabase.auth.getSession().then(({ data }) => {
      setSession(data.session);
      setLoading(false);
    });

    const { data: sub } = supabase.auth.onAuthStateChange((_event, newSession) => {
      setSession(newSession);
    });

    return () => sub.subscription.unsubscribe();
  }, []);

  const isAdmin = Boolean(session?.user?.email && session.user.email.toLowerCase() === ADMIN_EMAIL.toLowerCase());

  const value = useMemo<AuthContextValue>(
    () => ({
      session,
      loading,
      isAdmin,
      signIn: async (email, password) => {
        if (email.trim().toLowerCase() !== ADMIN_EMAIL.toLowerCase()) {
          return { error: UNAUTHORIZED_MSG };
        }
        const { error } = await supabase.auth.signInWithPassword({ email, password });
        return { error: error?.message ?? null };
      },
      signUp: async (email, password) => {
        if (email.trim().toLowerCase() !== ADMIN_EMAIL.toLowerCase()) {
          return { error: UNAUTHORIZED_MSG };
        }
        const { error } = await supabase.auth.signUp({ email, password });
        return { error: error?.message ?? null };
      },
      signOut: async () => {
        await supabase.auth.signOut();
      },
    }),
    [session, loading, isAdmin],
  );

  return <AuthContext.Provider value={value}>{children}</AuthContext.Provider>;
}

export function useAuth() {
  const ctx = useContext(AuthContext);
  if (!ctx) throw new Error('useAuth must be used within AuthProvider');
  return ctx;
}
